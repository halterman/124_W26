number = input("Please enter the English number: ")
if number == 'one':
    spanish_word = 'uno'
elif number == 'two':
    spanish_word = 'dos'
elif number == 'three':
    spanish_word = 'tres'
elif number == 'four':
    spanish_word = 'cuatro'
else:
    spanish_word = "???"
print(f'The Spanish equivalent is {spanish_word}')